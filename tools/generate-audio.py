#!/usr/bin/env python3
"""Generate natural-sounding recorded audio (neural voices) for every French text in TEF Quest.

  python3 tools/generate-audio.py --provider edge          # free, no account (unofficial Microsoft endpoint)
  python3 tools/generate-audio.py --provider azure         # official Azure Speech, free tier covers this project
  python3 tools/generate-audio.py --provider dummy         # silent clips, only to test the pipeline

Output: audio/<key>.mp3 and audio/manifest.js (the app plays a clip when it exists, otherwise uses browser voices).
Re-running only creates missing clips. Use --force to rebuild everything.

Azure:  export AZURE_SPEECH_KEY=...  AZURE_SPEECH_REGION=canadacentral
Edge:   pip install edge-tts
Terms:  the "edge" provider calls an undocumented Microsoft endpoint. For a public repository prefer "azure"
        (or any TTS whose license lets you redistribute the audio).
"""
import argparse, asyncio, json, os, subprocess, sys, time, urllib.request, urllib.error
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parent.parent
AUDIO = ROOT / "audio"


def audio_key(role: str, text: str) -> str:
    """Must match TEF.audioKey in js/audiokey.js (FNV-1a over UTF-8 of "role|text", plus byte length)."""
    s = (role + "|" + " ".join(text.split())).encode("utf-8")
    h = 0x811C9DC5
    for b in s:
        h ^= b
        h = (h * 0x01000193) & 0xFFFFFFFF
    return f"{h:08x}-{len(s)}"


def load_items():
    out = subprocess.run(["node", str(ROOT / "tools" / "extract-texts.js")], capture_output=True, text=True, check=True).stdout
    items = json.loads(out)
    for it in items:  # safety net: the JS and Python keys must agree
        assert audio_key(it["role"], it["text"]) == it["key"], f"key mismatch for {it['text']!r}"
    return items


async def run_edge(todo, voices, rate, conc):
    try:
        import edge_tts
    except ImportError:
        sys.exit("Install it first:  pip install edge-tts")
    sem = asyncio.Semaphore(conc)
    failed = []

    async def one(it):
        async with sem:
            path = AUDIO / f"{it['key']}.mp3"
            for attempt in range(4):
                try:
                    await edge_tts.Communicate(it["text"], voices[it["role"]], rate=rate).save(str(path))
                    if path.exists() and path.stat().st_size > 500:
                        return
                except Exception as e:  # network hiccup or throttling
                    err = e
                await asyncio.sleep(1.5 * (attempt + 1))
            failed.append((it["text"], str(err)))
            if path.exists():
                path.unlink()

    await asyncio.gather(*(one(it) for it in todo))
    return failed


def run_azure(todo, voices, rate):
    key, region = os.environ.get("AZURE_SPEECH_KEY"), os.environ.get("AZURE_SPEECH_REGION")
    if not key or not region:
        sys.exit("Set AZURE_SPEECH_KEY and AZURE_SPEECH_REGION (for example canadacentral).")
    url = f"https://{region}.tts.speech.microsoft.com/cognitiveservices/v1"
    failed = []
    for n, it in enumerate(todo, 1):
        voice = voices[it["role"]]
        ssml = (f"<speak version='1.0' xml:lang='fr-CA' xmlns='http://www.w3.org/2001/10/synthesis'>"
                f"<voice name='{voice}'><prosody rate='{rate}'>{escape(it['text'])}</prosody></voice></speak>")
        req = urllib.request.Request(url, data=ssml.encode("utf-8"), method="POST", headers={
            "Ocp-Apim-Subscription-Key": key, "Content-Type": "application/ssml+xml",
            "X-Microsoft-OutputFormat": "audio-24khz-48kbitrate-mono-mp3", "User-Agent": "tef-quest"})
        for attempt in range(4):
            try:
                with urllib.request.urlopen(req, timeout=30) as r:
                    (AUDIO / f"{it['key']}.mp3").write_bytes(r.read())
                break
            except urllib.error.HTTPError as e:
                if e.code == 429:
                    time.sleep(3 * (attempt + 1)); continue
                failed.append((it["text"], f"HTTP {e.code}")); break
            except Exception as e:
                time.sleep(2 * (attempt + 1))
                if attempt == 3:
                    failed.append((it["text"], str(e)))
        if n % 25 == 0:
            print(f"  {n}/{len(todo)}")
    return failed


def run_dummy(todo):
    for it in todo:
        subprocess.run(["ffmpeg", "-loglevel", "error", "-y", "-f", "lavfi", "-i", "anullsrc=r=24000:cl=mono", "-t", "0.2",
                        "-c:a", "libmp3lame", "-b:a", "32k", str(AUDIO / f"{it['key']}.mp3")], check=True)
    return []


def write_manifest(items):
    keys = sorted(it["key"] for it in items if (AUDIO / f"{it['key']}.mp3").exists())
    body = "{" + ",".join(f'"{k}":1' for k in keys) + "}"
    (AUDIO / "manifest.js").write_text(
        "/* Generated by tools/generate-audio.py. Lists the clips that exist in /audio. Empty means \"use browser voices\". */\n"
        "window.TEF = window.TEF || {};\nTEF.audio = " + body + ";\n", encoding="utf-8")
    return len(keys)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--provider", choices=["edge", "azure", "dummy"], required=True)
    ap.add_argument("--voice-a", default="fr-CA-SylvieNeural", help="main voice (default fr-CA-SylvieNeural)")
    ap.add_argument("--voice-b", default="fr-CA-AntoineNeural", help="second voice (default fr-CA-AntoineNeural)")
    ap.add_argument("--rate", default="-5%", help="speaking rate, default -5%% (a touch slower, good for learners)")
    ap.add_argument("--concurrency", type=int, default=4)
    ap.add_argument("--force", action="store_true", help="regenerate clips that already exist")
    ap.add_argument("--limit", type=int, default=0, help="only the first N missing clips (for a quick test)")
    ap.add_argument("--list", action="store_true", help="only print how many clips are needed")
    a = ap.parse_args()

    AUDIO.mkdir(exist_ok=True)
    items = load_items()
    chars = sum(len(i["text"]) for i in items)
    todo = [i for i in items if a.force or not (AUDIO / f"{i['key']}.mp3").exists()]
    print(f"{len(items)} clips needed ({chars:,} characters). {len(todo)} to generate.")
    if a.list:
        return
    if a.limit:
        todo = todo[: a.limit]
    voices = {"A": a.voice_a, "B": a.voice_b}
    if todo:
        if a.provider == "edge":
            failed = asyncio.run(run_edge(todo, voices, a.rate, a.concurrency))
        elif a.provider == "azure":
            failed = run_azure(todo, voices, a.rate)
        else:
            failed = run_dummy(todo)
        for t, e in failed[:10]:
            print("FAILED:", t[:60], "->", e)
        if failed:
            print(f"{len(failed)} clip(s) failed. Run again to retry only those.")
    n = write_manifest(items)
    size = sum(f.stat().st_size for f in AUDIO.glob("*.mp3")) / 1e6
    print(f"manifest lists {n} clips ({size:.1f} MB). Commit audio/ and push.")


if __name__ == "__main__":
    main()
